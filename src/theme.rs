#[derive(Clone, Copy)]
pub struct Theme {
    pub background: u32,
    pub background_alt: u32,
    pub foreground: u32,
    pub foreground_dim: u32,
    pub border: u32,
    pub heading: [u32; 4],
    pub heading_bullets: [&'static str; 4],
    pub code_background: u32,
    pub code_boundary_background: u32,
    pub code_block_accent: u32,
    pub code_foreground: u32,
    pub code_boundary: u32,
    pub quote: u32,
    pub link: u32,
    pub meta: u32,
    pub inline_code: u32,
    pub inline_code_background: u32,
    pub date: u32,
    pub keyword: u32,
    pub string: u32,
    pub comment: u32,
    pub type_name: u32,
    pub function: u32,
    pub constant: u32,
    pub number: u32,
    pub variable: u32,
    pub operator: u32,
    pub attribute: u32,
}

